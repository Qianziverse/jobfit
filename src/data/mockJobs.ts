export type CompanyTier = 'top' | 'mid' | 'small';

export interface Job {
  id: string;
  title: string;
  company: string;
  location: string;
  salary: string;
  platform: 'boss' | 'shixiseng' | 'official';
  type: 'fulltime' | 'intern';
  publishDate: string;
  deadline: string;
  matchScore: number;
  tags: string[];
  requirements: string[];
  description: string;
  logo: string;
  headcount: number;
  experience: string;
  education: string;
  badges: JobBadge[];
  /** 行业 id，对应 jobTaxonomy.ts 中的 Industry.id */
  industryId: string;
  /** 职能标签，对应 jobTaxonomy.ts 中 Industry.functions[].label，用于精准匹配 */
  jobFunction: string;
  internDaysPerWeek?: number;
  canConvert?: boolean;
  acceptRemote?: boolean;
  acceptNoExp?: boolean;
  /** 投递链接，跳转到对应平台的岗位页面 */
  applyUrl: string;
  /** 公司规模等级：top=头部大厂, mid=中型企业, small=小型/创业公司 */
  companyTier: CompanyTier;
}

